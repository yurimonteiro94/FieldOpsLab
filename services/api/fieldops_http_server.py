def route_payload(path: str) -> tuple[int, dict[str, Any]]:
    normalized_path = path.rstrip("/") or "/"

    if normalized_path == "/api/v1/health":
        return HTTPStatus.OK, health_payload()

    if normalized_path == "/api/v1/project-status":
        return HTTPStatus.OK, project_status_payload()

    if normalized_path == "/api/v1/reports":
        return HTTPStatus.OK, reports_payload()

    if normalized_path.startswith("/api/v1/reports/"):
        report_id = urllib.parse.unquote(
            normalized_path.removeprefix("/api/v1/reports/")
        )

        if not report_id or "/" in report_id:
            return HTTPStatus.NOT_FOUND, {
                "error": "report_not_found",
                "read_only": True,
                "available": False,
                "id": report_id,
                "known_report_ids": [item["id"] for item in REPORT_DEFINITIONS],
            }

        return report_detail_payload(report_id)

    if normalized_path == "/api/v1/experimental-design-matrix":
        return HTTPStatus.OK, experimental_design_payload()

    if normalized_path == "/api/v1/research-method":
        return HTTPStatus.OK, research_method_payload()

    if normalized_path == "/api/v1/simulation-state-contract":
        return HTTPStatus.OK, simulation_state_contract_payload()

    return HTTPStatus.NOT_FOUND, {
        "error": "not_found",
        "read_only": True,
        "path": path,
    }


class FieldOpsRequestHandler(BaseHTTPRequestHandler):
    server_version = "FieldOpsLabReadOnlyAPI/0.1"

    def log_message(self, format: str, *args: Any) -> None:
        return

    def send_json(self, status_code: int, payload: dict[str, Any]) -> None:
        body = json.dumps(payload, indent=2, sort_keys=True).encode("utf-8")

        self.send_response(status_code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Access-Control-Allow-Origin", "http://127.0.0.1:5173")
        self.send_header("Access-Control-Allow-Methods", "GET, HEAD, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type, Accept")
        self.end_headers()

        if self.command != "HEAD":
            self.wfile.write(body)

    def do_OPTIONS(self) -> None:
        self.send_response(HTTPStatus.NO_CONTENT)
        self.send_header("Access-Control-Allow-Origin", "http://127.0.0.1:5173")
        self.send_header("Access-Control-Allow-Methods", "GET, HEAD, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type, Accept")
        self.end_headers()

    def do_HEAD(self) -> None:
        status_code, payload = route_payload(self.path.split("?", 1)[0])
        self.send_json(status_code, payload)

    def do_GET(self) -> None:
        status_code, payload = route_payload(self.path.split("?", 1)[0])
        self.send_json(status_code, payload)

    def do_POST(self) -> None:
        self.send_json(
            HTTPStatus.METHOD_NOT_ALLOWED,
            {
                "error": "method_not_allowed",
                "read_only": True,
                "write_operations_supported": False,
                "execution_supported": False,
                "allows_arbitrary_command_execution": False,
                "allowed_methods": ["GET", "HEAD", "OPTIONS"],
            },
        )

    def do_PUT(self) -> None:
        self.do_POST()

    def do_PATCH(self) -> None:
        self.do_POST()

    def do_DELETE(self) -> None:
        self.do_POST()


def create_server(host: str, port: int, quiet: bool = False) -> ThreadingHTTPServer:
    return ThreadingHTTPServer((host, port), FieldOpsRequestHandler)


def read_url_json(url: str) -> tuple[int, dict[str, Any]]:
    request = urllib.request.Request(url, method="GET")

    try:
        with urllib.request.urlopen(request, timeout=5) as response:
            payload = json.loads(response.read().decode("utf-8"))
            return response.status, payload
    except urllib.error.HTTPError as error:
        try:
            payload = json.loads(error.read().decode("utf-8"))
            return error.code, payload
        finally:
            error.close()


def read_url_status_for_method(url: str, method: str) -> int:
    request = urllib.request.Request(url, method=method)

    try:
        with urllib.request.urlopen(request, timeout=5) as response:
            return response.status
    except urllib.error.HTTPError as error:
        try:
            return error.code
        finally:
            error.close()


def run_self_test() -> int:
    host = "127.0.0.1"
    server = create_server(host, 0)
    port = int(server.server_address[1])
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()

    try:
        base_url = f"http://{host}:{port}"

        expected_paths = [
            "/api/v1/health",
            "/api/v1/project-status",
            "/api/v1/reports",
            "/api/v1/reports/project_status",
            "/api/v1/reports/campaign_final_diagnostic_report",
            "/api/v1/experimental-design-matrix",
            "/api/v1/research-method",
            "/api/v1/simulation-state-contract",
        ]

        for path in expected_paths:
            status, payload = read_url_json(base_url + path)
            print(path, status)

            if status != HTTPStatus.OK:
                raise RuntimeError(f"Expected HTTP 200 for {path}, got {status}")

            if not payload.get("read_only", True):
                raise RuntimeError(f"Endpoint {path} did not preserve read-only contract")

        reports_status, reports_payload_data = read_url_json(base_url + "/api/v1/reports")

        if reports_status != HTTPStatus.OK:
            raise RuntimeError("Reports catalog endpoint is unavailable")

        report_ids = {
            report["id"]
            for report in reports_payload_data.get("reports", [])
            if isinstance(report, dict)
        }

        required_report_ids = {
            "campaign_index",
            "campaign_execution_index",
            "campaign_final_diagnostic_report",
            "campaign_result_summary",
            "full_campaign_pipeline",
        }

        missing_report_ids = required_report_ids - report_ids

        if missing_report_ids:
            raise RuntimeError(
                f"Reports catalog is missing campaign reports: {sorted(missing_report_ids)}"
            )

        detail_status, detail_payload = read_url_json(
            base_url + "/api/v1/reports/campaign_final_diagnostic_report"
        )

        if detail_status != HTTPStatus.OK:
            raise RuntimeError("Campaign final diagnostic report detail is unavailable")

        if detail_payload.get("id") != "campaign_final_diagnostic_report":
            raise RuntimeError("Report detail endpoint returned an unexpected campaign id")

        unknown_report_status = read_url_status_for_method(
            base_url + "/api/v1/reports/unknown_report",
            "GET",
        )
        print("GET /api/v1/reports/unknown_report", unknown_report_status)

        if unknown_report_status != HTTPStatus.NOT_FOUND:
            raise RuntimeError("Unknown report detail should return 404")

        post_status = read_url_status_for_method(base_url + "/api/v1/health", "POST")
        print("POST /api/v1/health", post_status)

        if post_status != HTTPStatus.METHOD_NOT_ALLOWED:
            raise RuntimeError("POST request should be rejected with 405")

        research_status, research_payload_data = read_url_json(
            base_url + "/api/v1/research-method"
        )

        if research_status != HTTPStatus.OK:
            raise RuntimeError("Research method endpoint is unavailable")

        research_conservative = research_payload_data.get(
            "conservative_interpretation", {}
        )

        if research_conservative.get("fuzzy_logic_is_optional") is not True:
            raise RuntimeError("Research method endpoint must keep fuzzy logic optional")

        if research_conservative.get("practical_equivalence_must_be_handled") is not True:
            raise RuntimeError("Research method endpoint must handle practical equivalence")

        simulation_status, simulation_payload_data = read_url_json(
            base_url + "/api/v1/simulation-state-contract"
        )

        if simulation_status != HTTPStatus.OK:
            raise RuntimeError("Simulation state contract endpoint is unavailable")

        simulation_conservative = simulation_payload_data.get(
            "conservative_interpretation", {}
        )

        if simulation_conservative.get("allows_browser_triggered_execution") is not False:
            raise RuntimeError("Simulation endpoint must not allow browser execution")

        if simulation_conservative.get("allows_arbitrary_command_execution") is not False:
            raise RuntimeError("Simulation endpoint must not allow arbitrary commands")

        if simulation_conservative.get("defines_future_safe_contract_only") is not True:
            raise RuntimeError("Simulation endpoint must expose contract-only status")

        print("FieldOps Lab read-only API self-test passed.")
        return 0
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)


def main() -> None:
    parser = argparse.ArgumentParser(description="FieldOps Lab read-only local HTTP API.")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8080)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()

    if args.self_test:
        raise SystemExit(run_self_test())

    server = create_server(args.host, args.port)

    print(f"FieldOps Lab read-only API listening on http://{args.host}:{args.port}")
    print("Allowed methods: GET, HEAD, OPTIONS")
    print("Execution endpoints are intentionally disabled.")

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        print("Stopping FieldOps Lab read-only API server.")
        server.server_close()
        time.sleep(0.1)


if __name__ == "__main__":
    main()