def read_json_file(
    path: Path,
    fallback: dict[str, Any] | None = None,
) -> dict[str, Any]:
    if not path.exists():
        return fallback or {}

    with path.open("r", encoding="utf-8") as file:
        payload = json.load(file)

    if isinstance(payload, dict):
        return payload

    return fallback or {}


def read_text_file(path: Path) -> str:
    if not path.exists():
        return ""

    return path.read_text(encoding="utf-8")


def path_exists_as_bool(path: Path) -> bool:
    return path.exists() and path.is_file()


def quality_passed_from_payload(payload: dict[str, Any]) -> bool | None:
    for key in [
        "passed",
        "all_required_checks_passed",
        "quality_gate_passed",
        "quality_check_passed",
    ]:
        value = payload.get(key)

        if isinstance(value, bool):
            return value

    return None


def read_json_resource(relative_path: str) -> dict[str, Any]:
    path = REPOSITORY_ROOT / relative_path

    if not path_exists_as_bool(path):
        return {
            "path": relative_path,
            "exists": False,
            "loaded": False,
            "data": None,
            "error": "missing_file",
        }

    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        return {
            "path": relative_path,
            "exists": True,
            "loaded": False,
            "data": None,
            "error": f"invalid_json: {error}",
        }

    return {
        "path": relative_path,
        "exists": True,
        "loaded": isinstance(payload, dict),
        "data": payload if isinstance(payload, dict) else None,
        "error": None if isinstance(payload, dict) else "json_root_is_not_object",
    }


def read_text_resource(relative_path: str) -> dict[str, Any]:
    path = REPOSITORY_ROOT / relative_path

    if not path_exists_as_bool(path):
        return {
            "path": relative_path,
            "exists": False,
            "loaded": False,
            "text": "",
            "error": "missing_file",
        }

    return {
        "path": relative_path,
        "exists": True,
        "loaded": True,
        "text": path.read_text(encoding="utf-8"),
        "error": None,
    }


